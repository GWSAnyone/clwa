    operation: { type: 'string', description: 'зачем вызвали — задача, простым языком (1-2 предложения)' },
    failure: { type: 'string', description: 'как именно сорвалось — вытекает из природы Отрицания (1-2 предложения)' },
    stakeVectorPole: { type: 'string', description: 'полюс выбора, кренящий в VECTOR (рвануть вовне, переписать чужой исход): что игрок делает и почему это кренит наружу' },
    stakeReclusePole: { type: 'string', description: 'полюс, кренящий в RECLUSE (замкнуться, не вынести момент): что игрок делает и почему это кренит внутрь' },
