phase('Generate')
const gens = (await parallel(ANCHORS.map((a) => () =>
  agent(
    WORLD + '\n\n' + RULES + '\n\n=== ТВОЙ ЯКОРЬ: ' + a.name + ' ===\n' + a.fuel +
    '\n\nВерни сцены строго по схеме. Каждая — уникальная Первая смена этого реликта. Оба полюса STAKE достижимы из траектории (НЕ бинарный выбор). Простой язык. Спойлер-границу не нарушать.',
    { label: 'gen:' + a.name, phase: 'Generate', schema: GEN_SCHEMA },
  ),
))).filter(Boolean)

const allScenarios = gens.flatMap((g) => g.scenarios || [])

phase('Critique')
const critic = await agent(
  WORLD + '\n\n' + RULES + '\n\n' +
  'Ты — придирчивый критик-редактор. Вот ВСЕ сгенерированные сцены Первой смены (JSON):\n\n' +
  JSON.stringify(allScenarios, null, 1) +
  '\n\nПроверь КАЖДУЮ сцену и вынеси вердикт (keep/fix/cut/merge) с разбором проблем по этим осям:\n' +
  '- ПОВТОР: не пересказ ли это другой сцены (того же реликта или другого). Сгруппируй дубли.\n' +
  '- ВАЛИДАТОРЫ: оба полюса STAKE реально достижимы из траектории (не бинарное меню)? FAILURE вытекает из природы Отрицания? OPERATION совместима с триажем Illa? Halden НИГДЕ не выступает как самостоятельно деплоимый инструмент (только через поле Mara или как жертва рядом)?\n' +
  '- СПОЙЛЕР: не протекает ли writer-only (DEXISTERE/R-0/дожать травму/Quies-поводок-по-умыслу/генезис фонда). Помечай id в spoilerFlags.\n' +
  '- ТОН/ЯЗЫК: простой язык, конкретная деталь, нет чистого выхода, тон PM/Disco.\n' +
  'Будь строг: лучше срезать слабое, чем оставить рескин. Цель — не меньше 15 СИЛЬНЫХ уникальных завязок из набора.',
  { label: 'critic', phase: 'Critique', schema: CRITIC_SCHEMA },
)

phase('Synthesize')
const synth = await agent(
  WORLD + '\n\n' + RULES + '\n\n' +
  'Ты — финальный синтезатор. Дано:\n\nСЦЕНЫ (JSON):\n' + JSON.stringify(allScenarios, null, 1) +
  '\n\nВЕРДИКТЫ КРИТИКА (JSON):\n' + JSON.stringify(critic, null, 1) +
  '\n\nСобери ФИНАЛЬНЫЙ пул: примени вердикты (срежь cut, слей merge-дубли, учти fix), оставь не меньше 15 сильных уникальных Первых смен по 4 якорям (Mara/Orin/Wren/Senna), Halden — вплетён через Mara.\n' +
  'finalPoolMd — готовый markdown под файл Design/Randomization.md: на каждого якоря таблица/список (OPERATION, FAILURE, полюс-Vector, полюс-Recluse), правило Halden через Mara, блок валидаторов совместимости, и явный счёт уникальных завязок. Простой язык, тон выдержан.\n' +
  'exemplars — 4 развёрнутых примера-камертона (по одному на якорь) в прозе, по образцу эталонной сцены Mara.\n' +
  'Спойлер-границу держать. Страж масштаба.',
  { label: 'synthesis', phase: 'Synthesize', schema: SYNTH_SCHEMA },
)

return { synth, critic, gens, scenarioCount: allScenarios.length }
